 assert.equal(await p.locator('[data-folder=instagib]').evaluate(n=>n.open),true);
 await p.locator('.model[data-model=railgun]').click();
 await p.waitForSelector('#viewport[data-state=ready][data-model=railgun]',{timeout:120000});
