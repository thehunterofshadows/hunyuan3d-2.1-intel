 assert.equal(await p.locator('[data-folder=pinball]').evaluate(n=>n.open),true);
 assert.equal(await p.locator('.model:visible').count(),1);
 assert.equal(await p.locator('.model[data-model=trellis-pinball-plunger]').isVisible(),true);
 await p.locator('#model-search').fill('no-such-model-123');
 assert.equal(await p.locator('#model-empty').isVisible(),true);
 await p.locator('#model-search').fill('');
 assert.equal(await p.locator('[data-folder=pinball]').evaluate(n=>n.open),false);
 assert.equal(await p.locator('[data-folder=instagib]').evaluate(n=>n.open),true);
 await p.goto(origin+'#portable-pinball',{waitUntil:'domcontentloaded'});
 await p.waitForSelector('#viewport[data-state=ready][data-model=portable-pinball]',{timeout:120000});
 assert.equal(await p.locator('[data-folder=pinball]').evaluate(n=>n.open),true);
 // Previously open folders remain open; deep links reveal their own folder without collapsing user choices.
 assert.equal(await p.locator('[data-folder=instagib]').evaluate(n=>n.open),true);
