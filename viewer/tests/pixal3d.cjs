const { chromium } = require('/opt/checks/node_modules/playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport:{width:1440,height:960}});
  const errors=[];
  page.on('pageerror', e=>errors.push(e.message));
  await page.goto((process.env.VIEWER_URL || 'http://intel-3d-studio-prod-web')+'/#pixal3d-railgun');
  await page.waitForSelector('#viewport[data-state=ready]', {timeout:90000});
  const stats=await page.locator('#stats').innerText();
  assert.match(stats,/triangles/);
  const name=await page.locator('#title').innerText();
  assert.match(name,/Pixal3D/);
  await page.click('[data-view=front]');
  await page.waitForTimeout(800);
  const file='/assets/pixal3d-railgun/preview.png';
  await page.locator('#viewport canvas').screenshot({path:file});
  assert.ok(fs.statSync(file).size>5000,'actual GLB screenshot');
  const url=new URL(await page.locator('#download').getAttribute('href'),page.url());
  const response=await page.request.get(url.href);
  assert.equal(response.status(),200);
  const blob=await response.body();
  assert.equal(blob.subarray(0,4).toString(),'glTF');
  assert.ok(blob.length>1000000,'real GLB binary');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS Pixal3D real model '+stats+' '+blob.length+' bytes');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
