const {chromium}=require('/opt/checks/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto(process.env.VIEWER_URL||'http://intel-3d-studio-prod-web/',{waitUntil:'domcontentloaded',timeout:60000});
await page.waitForSelector('#viewport[data-state=ready]',{timeout:60000});
const item=page.locator('button[data-model="railgun-detail-v2"]');
await item.evaluate(el=>el.closest('details').open=true);
await item.click();
await page.waitForSelector('#viewport[data-state=ready][data-model="railgun-detail-v2"]',{timeout:60000});
const stats=await page.locator('#stats').textContent();
assert.match(stats,/47,680/);
const uri=await page.locator('#download').getAttribute('href');
const response=await page.request.get(new URL(uri,page.url()).href);
assert.equal(response.status(),200);
const bytes=await response.body();
assert.equal(bytes.subarray(0,4).toString(),'glTF');
assert.ok(bytes.byteLength>1000000 && bytes.byteLength<4000000);
await page.screenshot({path:'/evidence/railgun-v2-actual-glb.png'});
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto(process.env.VIEWER_URL||'http://intel-3d-studio-prod-web/',{waitUntil:'domcontentloaded',timeout:60000});
await mobile.locator('button[data-model="railgun-detail-v2"]').evaluate(el=>el.closest('details').open=true);
await mobile.locator('button[data-model="railgun-detail-v2"]').tap();
await mobile.waitForSelector('#viewport[data-state=ready][data-model="railgun-detail-v2"]',{timeout:60000});
assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
assert.deepEqual(errors,[]);
console.log('PASS railgun-detail-v2 loaded actual GLB / 47,680 triangles / material viewport + mobile');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
