const {chromium}=require('/opt/checks/node_modules/playwright');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
(async()=>{
 const browser=await chromium.launch({args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const issues=[];page.on('pageerror',e=>issues.push(e.message));
 const origin=process.env.VIEWER_URL||'http://intel-3d-studio-prod-web/';
 await page.goto(origin+'#trellis-railgun-ultra',{waitUntil:'domcontentloaded'});
 await page.waitForSelector('#viewport[data-state=ready][data-model=trellis-railgun-ultra]',{timeout:120000});
 assert.match(await page.locator('#stats').innerText(),/287,762 triangles · 4096px textures/);
 const href=await page.locator('#download').getAttribute('href');
 const response=await page.request.get(new URL(href,page.url()).href);
 assert.equal(response.status(),200);
 const body=await response.body();
 assert.equal(crypto.createHash('sha256').update(body).digest('hex'),'6f3d445f235503ca3612ac4ab2725d1ba10a1f8f14bc6bba552060536664889b');
 await page.waitForTimeout(1000);
 await page.locator('#viewport canvas').screenshot({path:'/assets/trellis-railgun-ultra/preview.png'});
 await page.screenshot({path:'/evidence/ultra-railgun-desktop.png'});
 await page.locator('#surface').selectOption('clay');
 await page.waitForTimeout(300);
 await page.screenshot({path:'/evidence/ultra-railgun-clay.png'});
 await page.locator('#surface').selectOption('pbr').catch(async()=>{await page.locator('#surface').selectOption({index:0})});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
 await page.screenshot({path:'/evidence/ultra-railgun-mobile.png'});
 assert.deepEqual(issues,[]);
 console.log('PASS actual GLB render, 287762 triangles, original SHA256 download, clay mode, mobile layout');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
