const {chromium}=require('/opt/checks/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const origin=process.env.VIEWER_URL||'http://intel-3d-studio-prod-web/';
 await page.goto(origin+'#vx110-wood-dolly',{waitUntil:'domcontentloaded'});
 await page.waitForSelector('#viewport[data-state="ready"][data-model="vx110-wood-dolly"]',{timeout:120000});
 assert.equal(await page.locator('[data-folder="jetski"]').count(),1);
 assert.equal(await page.locator('.model[data-model="vx110-wood-dolly"]').count(),1);
 assert.match(await page.locator('#description').textContent(),/\$477\.91/);
 assert.match(await page.locator('#stats').textContent(),/93/);
 assert.equal(await page.locator('#dolly-plan').isVisible(),true);
 const model=await page.request.get(origin+'models/vx110-wood-dolly/vx110-wood-dolly.glb');
 assert.equal(model.status(),200);assert.equal((await model.body()).subarray(0,4).toString(),'glTF');
 const plan=await page.request.get(origin+'models/vx110-wood-dolly/BUILD_PLAN.md');
 assert.equal(plan.status(),200);assert.match(await plan.text(),/\$477\.91/);
 await page.locator('#viewport canvas').screenshot({path:'/evidence/vx110-preview.png'});
 await page.screenshot({path:'/evidence/vx110-fullpage.png',fullPage:true});
 await page.locator('[data-view="top"]').click();
 await page.locator('[data-view="left"]').click();
 await page.locator('#reset-camera').click();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: VX110 dolly GLB/parts, pricing plan, deep link, preview, camera and mobile.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
